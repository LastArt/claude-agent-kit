/**
 * Единственная очистка в файле — и для имён ключей, и для значений белого списка. Та же, что
 * в `events.mjs`: управляющие символы (в том числе нулевой байт, переводы строк и ANSI-escape)
 * заменяются пробелом, пробелы схлопываются. Длину режет вызывающий — потолки у имени ключа
 * и у значения разные.
 */
function clean(s) {
  return String(s == null ? '' : s)
    .replace(/[\x00-\x1F\x7F]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Имя ключа для печати в `--selftest`: очистка от управляющих символов плюс потолок длины. */
function cleanKey(k) {
  return clean(k).slice(0, KEY_PRINT_MAX) || '<пусто>';
}

function rel(p) {
  const r = path.relative(PROJECT_ROOT, p);
  return (!r || r.startsWith('..')) ? p : r.split(path.sep).join('/');
}

