#!/usr/bin/env node
/**
 * Маска ограждённых блоков markdown — ОДНА на весь набор.
 *
 * Общий модуль, а не копия в каждом хуке — тот же довод, что у `fingerprint()`
 * в `kit-fingerprint.mjs`: фенсы разбирают два места, пол класса риска (`analysePlan()`
 * в `task.mjs`) и проверка именных ссылок на код (`checkCodeRefs()` в `check-syntax.mjs`).
 * Разойдись они в понимании markdown — один и тот же текст в одном хуке считался бы примером,
 * а в другом живой строкой; ровно это и нашлось: пол фенсы маскировал, проверка ссылок нет,
 * и процитировать битую ссылку как образец «так не надо» было нельзя.
 *
 * ЧТО СЧИТАЕТСЯ ОГРАЖДЁННЫМ БЛОКОМ — записано дословно в докблоке `cmdClass()` в `task.mjs`:
 * это несущая деталь разбора плана, и менять правила здесь, не правя тот докблок, нельзя.
 *
 * `inside[i] === true` — строка i внутри фенса (или сама фенс). `unclosedFrom` — номер строки
 * (с единицы) открывающего токена, который так и не закрылся: незакрытый блок в конце файла
 * означает, что хвост не разобран, и вызывающий обязан сказать об этом замечанием,
 * а не промолчать.
 *
 * Строки приходят уже разрезанными, и способ резки — дело вызывающего: `task.mjs` режет
 * по `/\r?\n/`, `check-syntax.mjs` — по `\n`, оставляя `\r` в конце строки, потому что там
 * важны смещения в исходном тексте. На разбор это не влияет: `\r` попадает в info string
 * открывающего токена, а у закрывающего снимается `trim()`.
 */
export function fenceMask(lines) {
  const inside = new Array(lines.length).fill(false);
  let open = null;
  let openLine = -1;
  for (let i = 0; i < lines.length; i += 1) {
    const m = lines[i].match(/^ {0,3}(`{3,}|~{3,})(.*)$/);
    if (open === null) {
      if (m) { open = { ch: m[1][0], len: m[1].length }; openLine = i; inside[i] = true; }
      continue;
    }
    inside[i] = true;
    if (m && m[1][0] === open.ch && m[1].length >= open.len && m[2].trim() === '') open = null;
  }
  return { inside, unclosedFrom: open ? openLine + 1 : null };
}
