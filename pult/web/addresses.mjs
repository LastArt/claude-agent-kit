/**
 * АДРЕС НАЗНАЧЕНИЯ ПО ПРИЧИНЕ ОЖИДАНИЯ — чистая таблица без единого обращения к разметке.
 *
 * Пункт 7 договора с фазой 4: уведомление обязано ВЕСТИ, а не разворачивать окно. Смысл
 * уведомления — сократить путь от «меня ждут» до «я ответил»; то, которое доводит до окна
 * и бросает, экономит переключение между приложениями, а поиск места решения оставляет
 * человеку. Причина без адреса — молчание того же класса, что закрывала фаза 3.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ВЕТВЯМИ В `app.mjs`. Таблица обязана быть проверяемой машинно:
 * «у каждой из семи причин есть свой адрес» — утверждение, которое ломается тихо, когда
 * в набор добавляют восьмую причину. Здесь нет ни одного обращения к `document`, поэтому
 * её читает и обычный Node — этим пользуется проверка 9 в `pult/tools/page-check.mjs`.
 *
 * ГРАНИЦА УТВЕРЖДЕНИЯ НАЗЫВАЕТСЯ ПРЯМО: таблица отвечает, КУДА вести, и не отвечает, ЧТО
 * человек там увидит. Что адрес действительно открывает нужный экран — предмет ручного
 * пункта протокола приёмки и глаз человека.
 *
 * Список причин — копия `PENDING_REASONS` (`pult/config.mjs`): страница констант демона
 * не импортирует, поэтому копия вынужденная, и источник назван здесь.
 */

/** Семь причин ожидания, ровно как в `PENDING_REASONS`. */
export const PENDING_REASONS = Object.freeze([
  'awaiting_approval', 'awaiting_acceptance', 'blocked', 'gate_blocked',
  'stop_product', 'stop_technical', 'stop_security',
]);

/**
 * Адреса. Слово — машинное, его читает `goToReason()` в `pult/web/app.mjs`:
 *
 *   plan      карточка задачи и открытый `PLAN.md`;
 *   accept    экран приёмки задачи;
 *   state     карточка и открытый `STATE.md`;
 *   gate      полоса машинной приёмки и, если отчёт есть, открытый отчёт;
 *   terminal  вкладка терминала с подсказкой (сессия НЕ поднимается сама — правило фазы 2);
 *   card      адрес по умолчанию: карточка задачи.
 */
export const ADDRESSES = Object.freeze({
  awaiting_approval: 'plan',
  awaiting_acceptance: 'accept',
  blocked: 'state',
  gate_blocked: 'gate',
  stop_product: 'terminal',
  stop_technical: 'terminal',
  stop_security: 'terminal',
});

/** Адрес по умолчанию: причина не пришла или не опознана — прежнее поведение, карточка. */
export const DEFAULT_ADDRESS = 'card';

/** Адрес по причине. Чужое слово адресом не становится: возвращается умолчание. */
export function addressFor(reason) {
  if (typeof reason !== 'string' || !reason) return DEFAULT_ADDRESS;
  return Object.prototype.hasOwnProperty.call(ADDRESSES, reason) ? ADDRESSES[reason] : DEFAULT_ADDRESS;
}
