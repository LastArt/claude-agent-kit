//     читателя перечня;
//   • КОНФЛИКТ ПРАВИЛ — тот же путь при РАЗНЫХ видах. Так бывает на нетипичной машине:
//     дом внутри `C:\ProgramData`, дом, равный системному каталогу, `HOME=/root`
//     в контейнере, `HOME=/var/root` на macOS. Первая редакция этой функции оставляла
//     ПЕРВУЮ строку, а строки «точно» стоят в массиве раньше строк «вместе с содержимым», —
//     и правило молча СЛАБЕЛО: при `HOME=/root` содержимое `/root` открывалось, хотя
//     комментарий у `POSIX_SYSTEM_DIRS` обещает обратное.
//
// Поэтому слияние берёт САМЫЙ СИЛЬНЫЙ вид сверки среди строк с одним путём. Результат зависит
// ТОЛЬКО ОТ СОСТАВА строк, а не от их порядка: переставьте список как угодно — сила запрета
// не изменится. Это несущее свойство, потому что порядок строк следующая правка переставит
// не задумываясь.
//
// Что от порядка всё-таки зависит — и почему это не страшно: при РАВНОЙ силе остаётся первая
// строка, то есть меняться может только `kind`, то есть ЧЕЛОВЕЧЕСКАЯ ФОРМУЛИРОВКА причины
// в сообщении инструмента. Сила запрета — та же. Ослабить список перестановкой строк нельзя
// ни в одной конфигурации.
//
// Ключ сравнения путей в списке: на Windows регистр не значим. Один на слияние и на сверку —
// два разных ключа развели бы «что слито» и «что проверено».
const rowKey = (p) => (process.platform === 'win32' ? p.toLowerCase() : p);

// СИЛА ЗАПРЕТА ДЕРЖИТСЯ ЗДЕСЬ — И ТОЛЬКО ЗДЕСЬ. Это не оговорка, а главное, что нужно знать
// перед правкой этой функции: `rootDenyMatch()` (`pult/lib/registry.mjs`) ходит по УЖЕ СЛИТОМУ
// списку, и строки, выброшенной слиянием, для него не существует. Верните сюда «оставляем
// первую» — и дыра вернётся целиком, что бы ни делал `rootDenyMatch()` (проверено ревью
// 02.09.2026 подстановкой: `C:\WINDOWS\System32` при доме `C:\WINDOWS` снова открывался).
// Строгий выбор в `rootDenyMatch()` подстраховкой НЕ является: он выбирает среди строк,
// которые уже совпали, а любое совпадение и так даёт отказ, — он определяет ПРИЧИНУ, а не
// границу.
//
// Поэтому гарантия ниже сделана МАШИННОЙ, а не письменной: сверка на загрузке (после списка)
// требует, чтобы слитая строка несла максимум силы среди сырых строк с тем же путём. Правка,
// возвращающая «оставляем первую», роняет старт с внятным сообщением, а не открывает каталог
// молча — сегодня такую правку не ловит ни одна другая проба.
const mergeRows = (rows) => {
  const strongest = new Map();
  for (const row of rows) {
    const kept = strongest.get(rowKey(row.path));
    if (!kept || ROOT_MATCH_STRENGTH[row.match] > ROOT_MATCH_STRENGTH[kept.match]) {
      strongest.set(rowKey(row.path), row);
    }
  }
  return [...strongest.values()];
};

// Сырые строки — до слияния. Держатся отдельной константой ради сверки ниже: без них
// «слияние ничего не потеряло» проверить нечем.
const ROOT_DENY_RAW = process.platform === 'win32'
  ? [
    ...denyRow(HOME_DIR, ROOT_MATCH.EXACT, ROOT_KIND.HOME),
    ...denyRow(HOME_PARENT_DIR, ROOT_MATCH.EXACT, ROOT_KIND.HOME_PARENT),
    ...denyRow(KIT_MASTER_DIR, ROOT_MATCH.TREE, ROOT_KIND.KIT_MASTER),
    ...denyRow(process.env.APPDATA, ROOT_MATCH.EXACT, ROOT_KIND.APP_DATA),
    ...denyRow(process.env.LOCALAPPDATA, ROOT_MATCH.EXACT, ROOT_KIND.APP_DATA),
    ...denyRow(process.env.SystemRoot, ROOT_MATCH.TREE, ROOT_KIND.SYSTEM),
    ...denyRow(process.env.ProgramFiles, ROOT_MATCH.TREE, ROOT_KIND.SYSTEM),
    ...denyRow(process.env['ProgramFiles(x86)'], ROOT_MATCH.TREE, ROOT_KIND.SYSTEM),
    ...denyRow(process.env.ProgramData, ROOT_MATCH.TREE, ROOT_KIND.SYSTEM),
  ]
  : [
    ...denyRow(HOME_DIR, ROOT_MATCH.EXACT, ROOT_KIND.HOME),
    ...denyRow(HOME_PARENT_DIR, ROOT_MATCH.EXACT, ROOT_KIND.HOME_PARENT),
    ...POSIX_HOME_PARENTS.flatMap((d) => denyRow(d, ROOT_MATCH.EXACT, ROOT_KIND.HOME_PARENT)),
    ...denyRow(KIT_MASTER_DIR, ROOT_MATCH.TREE, ROOT_KIND.KIT_MASTER),
    ...POSIX_SYSTEM_DIRS.flatMap((d) => denyRow(d, ROOT_MATCH.TREE, ROOT_KIND.SYSTEM)),
  ];

export const ROOT_DENY = Object.freeze(mergeRows(ROOT_DENY_RAW));

// СВЕРКА НА ЗАГРУЗКЕ: СЛИЯНИЕ НЕ ИМЕЕТ ПРАВА ОСЛАБИТЬ СПИСОК.
//
// Для каждой сырой строки слитая строка с тем же путём обязана нести НЕ МЕНЬШУЮ силу сверки.
// Утверждение, ради которого всё это писалось, становится проверяемым, а не письменным:
// правка `mergeRows()` до «оставляем первую» роняет старт с внятным сообщением вместо того,
// чтобы молча открыть системный каталог на нетипичной машине (находка ревью 02.09.2026).
// Лекарство и место те же, что у сверки словаря ожидающих статусов выше: файл — константы
// без ввода-вывода, расхождение возможно только при правке ЭТОГО файла, и падение на старте
// здесь дешевле открытой границы.
//
// В сообщение идёт ВИД запрета, а не путь: вид — наше машинное слово из закрытого словаря,
// а путь несёт имя пользователя и уехал бы в stdout демона.
for (const raw of ROOT_DENY_RAW) {
  const kept = ROOT_DENY.find((r) => rowKey(r.path) === rowKey(raw.path));
  if (!kept || ROOT_MATCH_STRENGTH[kept.match] < ROOT_MATCH_STRENGTH[raw.match]) {
    throw new Error(`pult/config.mjs: слияние строк ROOT_DENY ослабило запрет «${raw.kind}»`);
  }
}



