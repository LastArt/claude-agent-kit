#!/usr/bin/env node
/**
 * Завести проект в реестре пульта.
 *
 *   node pult/tools/registry-add.mjs <путь к проекту>
 *
 * Это ЕДИНСТВЕННЫЙ способ добавить проект: маршрута, принимающего путь проекта из запроса,
 * у демона нет и быть не должно. В кит инструмент не пишет ничего — только в реестр пульта,
 * который лежит в профиле пользователя.
 *
 * С ФАЗЫ 3 ИНСТРУМЕНТ НЕ ТОЛЬКО КОНСОЛЬНЫЙ: его запускает подпроцессом оболочка, а поток
 * ошибок показывает человеку в окне. Отсюда два свойства, которые надо держать:
 *   • отказ обязан ЧИТАТЬСЯ, а не расшифровываться по машинному коду;
 *   • В ПОТОК ОШИБОК НЕ ПЕЧАТАЕТСЯ ПРИСЛАННЫЙ ПУТЬ НИ В ОДНОЙ ВЕТВИ. Это уже так, и это надо
 *     сохранить: поток ошибок уезжает в окно, а стандартный вывод с перечнем всех записей
 *     реестра — не уезжает.
 * Коды возврата тоже читает оболочка: 0 — записано или уже было, 3 — отказ.
 *
 * Санитария входа (аргумент приходит из командной строки человека, но проверяется как чужой):
 *   • нулевой байт и управляющие символы — отказ;
 *   • длина сверх потолка — отказ;
 *   • сетевая (UNC) форма — отказ с объяснением: `stat` по такому пути уходит в сеть к чужому
 *     хосту с попыткой аутентификации, поддержки нет намеренно;
 *   • путь приводится `resolve`, затем `realpath` — в реестр пишется РАЗРЕШЁННЫЙ путь,
 *     иначе один и тот же проект попадёт в реестр дважды под разными именами (и заодно
 *     в реестр ложится каноническая длинная форма, на которой строковая сверка корня
 *     не промахивается);
 *   • путь обязан существовать и быть каталогом по `lstat` (не симлинком на каталог);
 *   • КАТАЛОГ ОБЯЗАН БЫТЬ ДОПУСТИМЫМ КОРНЕМ ПРОЕКТА. Проверяет это `addProject()`
 *     в `pult/lib/registry.mjs`; здесь причина отказа переводится человеку. Проверка нужна
 *     потому, что корень из реестра служит границей ВСЕМ проверкам пути в демоне: корень,
 *     равный домашнему каталогу, отдал бы через дерево и файл весь поддерев, а сессией
 *     терминала — оболочку машины в доме. «Любой абсолютный путь» здесь и был дефектом.
 *
 * Повторный запуск с тем же путём дубля не создаёт.
 */

import path from 'node:path';
import process from 'node:process';

import { statSafe, realPath, isUncPath, sanePath, capText } from '../lib/fs-safe.mjs';
import { addProject, readRegistry, registryFile } from '../lib/registry.mjs';
import { MAX_PATH, FAULT, ROOT_KIND } from '../config.mjs';

const TAG = '[pult]';
const out = (s = '') => process.stdout.write(`${s}\n`);
const err = (s = '') => process.stderr.write(`${TAG} ${s}\n`);

/**
 * Вид запрещённого корня — человеку. Ключи из закрытого словаря `ROOT_KIND`, то есть
 * это перевод машинного слова, а не второй список видов.
 */
const ROOT_REASON = Object.freeze({
  [ROOT_KIND.DRIVE_ROOT]: 'это корень диска (или корень файловой системы)',
  [ROOT_KIND.HOME]: 'это домашний каталог сам по себе — его ПОДКАТАЛОГИ завести можно',
  [ROOT_KIND.HOME_PARENT]: 'это каталог, в котором лежат домашние каталоги, — сам он проектом не бывает',
  [ROOT_KIND.KIT_MASTER]: 'это каталог набора в домашнем (мастер-копия) — он и всё его содержимое',
  [ROOT_KIND.APP_DATA]: 'это сам каталог данных приложений — его ПОДКАТАЛОГИ завести можно',
  [ROOT_KIND.SYSTEM]: 'это системный каталог — он и всё его содержимое',
  [ROOT_KIND.REGISTRY]: 'это каталог реестра самого пульта',
});

function usage() {
  out('Завести проект в реестре пульта:');
  out('  node pult/tools/registry-add.mjs <путь к проекту>');
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length !== 1 || args[0] === '--help' || args[0] === '-h') {
    usage();
    return args.length === 1 ? 0 : 3;
  }

  const raw = args[0];
  if (!sanePath(raw)) {
    err('путь пуст, длиннее потолка или содержит управляющие символы');
    return 3;
  }
  if (raw.length > MAX_PATH) {
    err(`путь длиннее потолка (${MAX_PATH})`);
    return 3;
  }
  if (isUncPath(raw)) {
    err('сетевой (UNC) путь на фазе 1 не поддерживается намеренно:');
    err('обращение к нему уходит в сеть к чужому хосту с попыткой аутентификации');
    return 3;
  }

  const resolved = path.resolve(raw);
  const real = await realPath(resolved);
  if (!real.ok) {
    err(`путь недоступен: ${real.code}`);
    return 3;
  }
  if (isUncPath(real.path)) {
    err('после разрешения ссылок путь оказался сетевым (UNC) — отказ по той же причине');
    return 3;
  }

  const st = await statSafe(real.path);
  if (!st.ok) {
    err(`путь недоступен: ${st.code}`);
    return 3;
  }
  if (!st.stat.isDirectory()) {
    err('это не каталог: в реестр попадает корень проекта, а не файл');
    return 3;
  }

  const name = capText(path.basename(real.path)).text;
  const res = await addProject(real.path, name);
  if (!res.ok) {
    // ОТДЕЛЬНАЯ ВЕТВЬ ДО ОБЩЕЙ СТРОКИ: этот отказ читает человек в окне оболочки, и «не
    // записал: root_rejected» ему не говорит ничего. Путь в поток ошибок по-прежнему
    // не печатается — человек его только что выбрал сам.
    if (res.code === FAULT.ROOT_REJECTED) {
      err('выбранный каталог отвергнут как КОРЕНЬ ПРОЕКТА:');
      err(`  ${ROOT_REASON[res.kind] || 'запрещённый корень'}`);
      err('корень из реестра служит границей всем проверкам пути в демоне: что назначено');
      err('корнем, то демон и готов читать и править. Поэтому корнем бывает только сама');
      err('папка проекта.');
      err('что делать: выбрать папку САМОГО ПРОЕКТА, а не каталог, в котором он лежит');
      return 3;
    }
    err(`не записал: ${res.code}`);
    return 3;
  }

  out(res.added ? `добавлено: ${res.entry.id} ${res.entry.name}` : `уже в реестре: ${res.entry.id} ${res.entry.name}`);
  out(`реестр: ${registryFile()}`);
  out('');
  const reg = await readRegistry();
  out(`записей: ${reg.entries.length}`);
  for (const e of reg.entries) {
    out(`  ${e.id}  ${e.name}  ${e.path}  просмотр: ${e.seen ? e.seen.value : '-'}`);
  }
  if (reg.faults.length) out(`отказы разбора: ${reg.faults.map((f) => f.code).join(', ')}`);
  return 0;
}

main().then((code) => process.exit(code)).catch((e) => {
  err(`не отработал: ${(e && (e.code || e.name)) || 'ошибка'}`);
  process.exit(3);
});
