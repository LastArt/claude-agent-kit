import path from 'node:path';

import { statSafe, makeBudget, capText } from '../lib/fs-safe.mjs';
import { readRegistry } from '../lib/registry.mjs';
import { readTasks } from './tasks.mjs';
import { readGate } from './gate.mjs';
import {
  FAULT, BUDGET_PENDING, PENDING_PROBE_MS, PENDING_REASONS, WAITING_STATUSES, MAX_PROJECTS,
} from '../config.mjs';

/** Причины — множеством: наружу не уходит слово, которого нет в закрытом словаре. */
const REASONS = new Set(PENDING_REASONS);

/**
 * Проба доступности в гонке со СВОИМ таймаутом.
 *
 * Как и у читателя проекта, идёт через `statSafe()` (то есть через `lstat`): обычный `stat`
 * в самом раннем обращении к чужому пути ушёл бы за симлинк. И так же честно: таймаут
 * защищает только саму пробу — зависший системный вызов продолжает держать поток пула
 * файловых операций и после того, как гонка вернула отказ.
 */
async function probe(target, ms) {
  let timer = null;
  const timeout = new Promise((resolve) => {
    timer = setTimeout(() => resolve({ ok: false, code: FAULT.READ_TIMEOUT }), ms);
  });
  try {
    return await Promise.race([statSafe(target), timeout]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}

/**
 * Причина ожидания — ОДНА, по упорядоченному правилу, и порядок здесь несущий:
 *
 *   1. заблокированная приёмка важнее статуса задачи (дальше не двинется ничто);
 *   2. вид стопа важнее общего «заблокировано» (человеку нужен вид, а не факт);
 *   3. иначе — сам статус задачи, если он из числа ожидающих человека.
 *
 * Слово сверяется с закрытым словарём ПЕРЕД возвратом: собранное строкой имя вида стопа
 * иначе уехало бы наружу без проверки.
 */
function pickReason(gateStatus, task) {
  if (gateStatus === 'blocked') return 'gate_blocked';
  const status = task && task.status ? task.status : null;
  if (!status || !WAITING_STATUSES.includes(status)) return null;
  const kind = task.stop_kind;
  if (status === 'blocked' && kind && kind !== '-') {
    const word = `stop_${kind}`;
    return REASONS.has(word) ? word : status;
  }
  return REASONS.has(status) ? status : null;
}

/**
 * Что ждёт человека прямо сейчас — по всем проектам реестра.
 *
 * @returns {{generated_at: string, pending: Array}} пустой список означает «ничего не ждёт» —
 *          но только вместе с отсутствием признаков неполноты (см. шапку модуля)
 */
export async function readPending() {
  const registry = await readRegistry();
  const budget = makeBudget(BUDGET_PENDING);
  const pending = [];

  // Потолок числа проектов тот же, что у списка: дальше первых записей демон и сам не читает.
  const entries = registry.entries.slice(0, MAX_PROJECTS);
  // Обрыв хода отмечается, а не проглатывается: без этого один повисший сетевой корень
  // в начале реестра выедает бюджет двумя пробами и закрывает собой ВСЕ ждущие проекты
  // после себя — молча.
  let cut = false;

  for (const entry of entries) {
    // Отвергнутый корень — мимо, до всякого обращения к диску.
    if (entry.rejected) continue;
    if (budget.tick()) { cut = true; break; }

    const rootStat = await probe(entry.path, PENDING_PROBE_MS);
    if (!rootStat.ok || !rootStat.stat.isDirectory()) continue;
    const kitDir = path.join(entry.path, '.claude');
    const kitStat = await probe(kitDir, PENDING_PROBE_MS);
    if (!kitStat.ok || !kitStat.stat.isDirectory()) continue;

    let tasks = { items: [], active: null };
    try {
      tasks = await readTasks(kitDir, { budget });
    } catch {
      continue;                       // нечитаемые задачи — молча мимо: это не ответ «ждёт»
    }

    let gateStatus = null;
    try {
      // ПРИЗНАК «БЕЗ ОТЧЁТА ПРИЁМКИ»: файл отчёта здесь не открывается вовсе.
      const g = await readGate(kitDir, { budget, report: false });
      gateStatus = g.gate ? g.gate.status : null;
    } catch {
      gateStatus = null;
    }

    const activeItem = tasks.active ? tasks.items.find((i) => i.task.id === tasks.active) : null;
    const task = activeItem ? activeItem.task : null;
    const reason = pickReason(gateStatus, task);
    if (!reason) continue;

    // ПОЛЯ ПЕРЕНОСЯТСЯ ПОИМЁННО. Свободный текст — через очистку и потолок ещё раз: гарантия
    // обязана быть видна здесь, а не подразумеваться из того, что кто-то очистил его раньше.
    pending.push({
      project: {
        id: entry.id,
        name: capText(entry.name).text,
      },
      task: task
        ? {
          id: task.id,
          title: task.title ? capText(task.title).text : null,
          status: task.status,
          stop_kind: task.stop_kind,
          updated: task.updated,
        }
        : null,
      gate: { status: gateStatus },
      reason,
    });
  }

  const body = { generated_at: new Date().toISOString(), pending };
  // ПОЛЯ НЕПОЛНОТЫ ДОБАВЛЯЮТСЯ, ТОЛЬКО КОГДА ЕСТЬ ЧТО СКАЗАТЬ, — так же это делает `collect()`.
  // Наружу уходят КОДЫ разбора, а не сообщения: список отказов реестра собран из наших
  // машинных слов (`{field, code}`), чужой текст в него не попадает по построению.
  if (registry.faults.length) body.registry_faults = registry.faults;
  if (registry.entries.length > entries.length) body.projects_truncated = true;
  // Бюджет считается исчерпанным и тогда, когда его добрал читатель задач или приёмки внутри
  // цикла: там `take()` вернул код, проект тихо остался без ответа, и это тоже неполнота.
  if (cut || budget.exhausted) body.pending_truncated = true;
  return body;
}
