#!/usr/bin/env node
/**
 * Чтение ОДНОГО файла проекта — для редактора в центре и для рабочей стороны сравнения.
 *
 * ПУТЬ ПРОВЕРЯЕТСЯ ТЕМ ЖЕ ПОРЯДКОМ И ТОЙ ЖЕ ФУНКЦИЕЙ, что и запись: `resolveTarget()`
 * в `pult/lib/fs-safe.mjs`, режим чтения. Своего порядка проверок здесь нет намеренно —
 * два соседних читателя с разными порядками при первой же правке сходятся по слабому.
 * Дальше работа идёт по РАЗРЕШЁННОМУ пути, а не по присланной строке.
 *
 * ПРЯМОГО `node:fs` В ЭТОМ ФАЙЛЕ НЕТ.
 *
 * СЕКРЕТЫ. Правило имени живёт в ШЛЮЗЕ (`isSecretPath()` в `pult/lib/fs-safe.mjs`), а сюда
 * только зовётся: одним и тем же правилом обязаны пользоваться умолчание чтения, отказ режима
 * записи, признак `writable` и пометка в дереве. Совпало — содержимое НЕ отдаётся: уходят код
 * отказа и признак «это секрет». Отдать такой файл можно только по ЯВНОМУ признаку в запросе,
 * и тогда демон печатает строку в stdout.
 *
 * Умолчание здесь обратное сегодняшнему намеренно: набор уже решил правилами `deny`, что эти
 * файлы не должны уезжать в чужой процесс, а демон заводит к ним ВТОРУЮ дорогу — и она обязана
 * быть по умолчанию закрытой. Но это УМОЛЧАНИЕ, А НЕ СТЕНА: локальному процессу оно
 * не мешает — тот же файл читается обычным `cat`. Смысл умолчания в том, что осознанное
 * действие видно (признак в запросе, строка в stdout, пометка в дереве), а неосознанного
 * не происходит.
 *
 * АСИММЕТРИЯ С ЗАПИСЬЮ — НАМЕРЕННАЯ И НАЗВАННАЯ. У чтения секрет закрыт умолчанием, у записи —
 * насовсем: парного признаку `reveal` ключа у сохранения нет, и `readonly` у такого файла
 * приходит `true` всегда (признак берётся у шлюза). Обоснование выбора — у `writeRefusal()`
 * в `pult/lib/fs-safe.mjs`; коротко: показ обратим и оставляет след, перезапись `.env` — нет.
 *
 * ДВОИЧНЫЙ ФАЙЛ НЕ ОТДАЁТСЯ ВОВСЕ. Байты, не переживающие круг «в строку UTF-8 и обратно»
 * (`isRoundTripUtf8()` ниже), — это либо двоичный файл, либо файл в чужой однобайтной
 * кодировке. Такой файл уходит отказом `not_text_file` с признаком `binary`, и содержимого
 * в ответе нет: иначе круг «открыл → сохранил» уничтожил бы его молча, а обещание записи
 * «байт в байт присланным» при этом формально держалось бы.
 *
 * НАРУЖУ УХОДЯТ ТОЛЬКО ПОЛЯ БЕЛОГО СПИСКА: содержимое, признак «запись запрещена», признак
 * секрета, признак двоичного файла, признак усечения и ТОКЕН СОСТОЯНИЯ.
 *
 * ТОКЕН — шестнадцатеричная строка от размера, метки изменения и хеша содержимого. Он
 * непрозрачен НАМЕРЕННО: он не время и вида времени не несёт, поэтому правило «все времена
 * наружу через единственную дверь `timeField()`» им не обходится. Нужен он сверке при
 * сохранении (`pult/write/file.mjs`) и больше нигде.
 */

import { createHash } from 'node:crypto';

import { resolveTarget, readBytesCapped, isSecretPath } from '../lib/fs-safe.mjs';
import { FAULT, MAX_EDIT_FILE } from '../config.mjs';

/**
 * Переживают ли байты круг «в строку и обратно».
 *
 * ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ НА ЗАПИСИ. Читатель отдавал содержимое строкой UTF-8, не проверяя,
 * что байты вообще UTF-8, а писатель кодирует строку обратно. Круг «открыл → сохранил»
 * УНИЧТОЖАЕТ такой файл: недекодируемые байты становятся заменяющим символом `U+FFFD`,
 * и обратное кодирование даёт другую длину и другое содержимое (замер ревью: PNG в 39 байт
 * после круга стал 33). Обещание записи «байт в байт присланным» при этом формально
 * держится — рушится файл ДО неё, поэтому лечение стоит на чтении.
 *
 * Сравниваются именно байты, а не «похоже ли на текст»: эвристика по нулевому байту пропустила
 * бы файл в CP1251, где нулей нет, а кириллица всё равно не декодируется. Круг же отвечает
 * ровно на тот вопрос, который важен: вернём ли мы на диск то, что взяли.
 *
 * Цена — одно лишнее кодирование файла в памяти, потолок у него общий (`MAX_EDIT_FILE`).
 */
export function isRoundTripUtf8(buf, text) {
  return Buffer.from(text, 'utf8').equals(buf);
}

/**
 * Токен состояния файла: размер, метка изменения и хеш содержимого — в одну строку.
 *
 * Это НЕ блокировка и защита не от агента, а от гонки: двое пишут одно место, и сверка
 * ловит момент. Помешать агенту писать она не может и не должна.
 */
export function stateToken(stat, buf) {
  const mtime = Number.isFinite(stat && stat.mtimeMs) ? Math.trunc(stat.mtimeMs) : 0;
  const size = Number.isFinite(stat && stat.size) ? stat.size : 0;
  return createHash('sha256')
    .update(`${size}:${mtime}:`, 'utf8')
    .update(buf)
    .digest('hex')
    .slice(0, 32);
}

/**
 * Прочитать файл проекта.
 *
 * @param {string} root      корень проекта из записи реестра
 * @param {string} rel       относительный путь от клиента
 * @param {object} options   `reveal: true` — отдать файл, попавший под образец секрета
 *                           (ставит его только маршрут по явному признаку в запросе)
 */
export async function readProjectFile(root, rel, options = {}) {
  const reveal = options.reveal === true;

  const t = await resolveTarget(root, rel, { mode: 'read', kind: 'file' });
  if (!t.ok) {
    return {
      ok: false, code: t.code, secret: false, readonly: false, binary: false,
      truncated: false, text: null, token: null,
    };
  }
  // ПРИЗНАК ЗАПИСИ БЕРЁТСЯ У ШЛЮЗА, а не считается здесь заново по одному условию «внутри
  // набора»: у проекта без набора (`no_kit`) запись отказывает всегда, и признак обязан
  // об этом говорить, иначе страница нарисует активную кнопку-обманку.
  const readonly = t.writable !== true;

  const secret = isSecretPath(t.path);
  if (secret && !reveal) {
    // Ни размера, ни метки времени, ни содержимого: наружу уходит только то, что файл есть
    // и что он закрыт умолчанием.
    return {
      ok: false, code: FAULT.SECRET_HIDDEN, secret: true, readonly, binary: false,
      truncated: false, text: null, token: null,
    };
  }

  const size = t.stat ? t.stat.size : 0;
  if (size > MAX_EDIT_FILE) {
    // Половина файла для редактора хуже отказа: сохранение такой половины уничтожило бы
    // хвост. Поэтому содержимого нет вовсе, а признак усечения говорит, почему.
    return {
      ok: false, code: FAULT.FILE_TOO_BIG, secret, readonly, binary: false,
      truncated: true, text: null, token: null,
    };
  }

  const read = await readBytesCapped(t.path, MAX_EDIT_FILE);
  if (!read.ok) {
    return {
      ok: false, code: read.code, secret, readonly, binary: false,
      truncated: false, text: null, token: null,
    };
  }

  const text = read.buf.toString('utf8');
  if (!isRoundTripUtf8(read.buf, text)) {
    // Содержимого НЕТ вовсе — и это не осторожность, а единственное, что спасает файл:
    // такую строку редактор вернул бы на сохранение, а обратное кодирование дало бы другие
    // байты. Признак `binary` нужен странице, чтобы открыть файл на просмотр, а не в редактор.
    return {
      ok: false, code: FAULT.NOT_TEXT_FILE, secret, readonly, binary: true,
      truncated: false, text: null, token: null,
    };
  }

  return {
    ok: true,
    code: null,
    // Внутри набора и в проекте без набора файл ПОКАЗЫВАЕТСЯ, но запись в него запрещена
    // шлюзом — признак нужен странице, чтобы кнопка сохранения была неактивной, а не отдавала
    // отказ по клику.
    readonly,
    secret,
    binary: false,
    truncated: false,
    text,
    token: stateToken(t.stat, read.buf),
  };
}
