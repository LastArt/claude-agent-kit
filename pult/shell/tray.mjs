#!/usr/bin/env node
/**
 * ИКОНКА В ОБЛАСТИ УВЕДОМЛЕНИЙ И ЕЁ МЕНЮ.
 *
 * Пунктов четыре:
 *   1. показать окно;
 *   2. открыть страницу в браузере — АДРЕСОМ ИЗ КОНСТАНТ, а не из строки. Это живое
 *      доказательство пункта 1 критерия готовности фазы: пульт работает и без оболочки;
 *   3. состояние демона строкой — свой или внешний. Пункт неактивен и служит подписью;
 *   4. выход — единственный способ завершить приложение (закрытие окна прячет его в трей).
 *
 * КАРТИНКА ИКОНКИ СТРОИТСЯ В КОДЕ из растрового буфера, а не приезжает файлом: двоичных
 * ресурсов в репозитории не заводим — они требуют своей строки в правилах окончаний строк
 * (`.gitattributes`) и не переживают правку текстовым инструментом.
 *
 * ЧТО ЗНАЧИТ «ЗНАЧОК ГОДЕН»: непрозрачных точек в буфере не меньше доли полотна
 * (`ICON_MIN_OPAQUE_SHARE`) И библиотека считает изображение непустым. Два разных вопроса,
 * а не один дважды: `isEmpty()` на полностью прозрачной картинке отвечает «не пусто».
 *
 * НЕ ПОСТРОИЛАСЬ — ТРЕЙ СОЗДАЁТСЯ ВСЁ РАВНО (без него нет запасного пути уведомлений,
 * `pult/shell/notify.mjs`), НО ОТЧЁТ ГОВОРИТ `ok: false`, и главный процесс перестаёт считать
 * трей способом вернуться и выйти. Раньше здесь стояло «пустая иконка не беда, меню работает»,
 * и это было неправдой: **пустой значок на Windows невидим**, меню открывать нечем, а окно
 * при закрытии пряталось именно туда. Приложение оставалось жить без единого способа его
 * закрыть, кроме диспетчера задач (находка человека 02.09.2026, дефекты 1 и 3).
 *
 * ВАЖНОЕ РАЗЛИЧЕНИЕ, КОТОРОЕ ЭТОТ КОД СДЕЛАТЬ НЕ МОЖЕТ: «значок не построился» и «значок
 * построился, но система спрятала его в переполнение» — разные вещи, и вторую Windows
 * не сообщает никак. Отсюда правило главного процесса: **прятать окно только когда есть куда
 * вернуться**, и говорить человеку словами, куда именно оно спряталось.
 *
 * ПОДСКАЗКА ИКОНКИ показывает, сколько задач ждёт человека, — дешёвый постоянный индикатор
 * и запасной канал сообщения. Текст в неё идёт через очистку и СВОЙ КОРОТКИЙ ПОТОЛОК,
 * и делает это вызывающий (`notify.mjs`): очистка чужого свободного текста живёт там же,
 * где остальные его потолки.
 */

import process from 'node:process';

import { Menu, Tray, nativeImage, shell } from 'electron';

import { PULT_URL, daemonState } from './daemon.mjs';

/** Сторона картинки в точках. 32 — то, что Windows уменьшает без каши. */
const ICON_SIZE = 32;

/** Наименьшая доля непрозрачных точек, при которой значок вообще виден. Обоснование — в `buildIcon()`. */
const ICON_MIN_OPAQUE_SHARE = 0.1;

const say = (s) => process.stdout.write(`[shell] ${s}\n`);

let tray = null;
let handlers = { onShow: () => {}, onQuit: () => {} };
let tipText = 'Пульт';

/**
 * Картинка из растрового буфера: круг с кольцом внутри — узнаваемо в мелком размере
 * и не требует ни шрифта, ни файла. Байты идут в порядке BGRA, как ждёт `createFromBitmap()`.
 */
export function buildIcon() {
  try {
    const size = ICON_SIZE;
    const buf = Buffer.alloc(size * size * 4);
    const c = (size - 1) / 2;
    for (let y = 0; y < size; y += 1) {
      for (let x = 0; x < size; x += 1) {
        const d = Math.hypot(x - c, y - c);
        let color = null;
        if (d <= 15) color = [235, 99, 37];              // синий круг (B, G, R)
        if (d <= 11 && d >= 8) color = [255, 255, 255];  // светлое кольцо
        if (d <= 3) color = [255, 255, 255];             // точка в центре
        if (!color) continue;
        const i = (y * size + x) * 4;
        buf[i] = color[0];
        buf[i + 1] = color[1];
        buf[i + 2] = color[2];
        buf[i + 3] = 255;
      }
    }
    // СЧИТАЕМ НЕПРОЗРАЧНЫЕ ТОЧКИ В СВОЁМ БУФЕРЕ, а не спрашиваем библиотеку.
    //
    // Находка ревью 02.09.2026: `isEmpty()` на ПОЛНОСТЬЮ ПРОЗРАЧНОЙ картинке 32×32 отвечает
    // `false`, и `new Tray()` такую картинку принимает — то есть «пусто» у библиотеки значит
    // «нет пикселей вовсе», а не «нечего показать». От этого признака теперь зависит,
    // останется ли приложение закрываемым, и такой предикат для него слишком слаб.
    //
    // Замер здорового значка: 716 непрозрачных точек из 1024 (около 70% — круг радиуса 15).
    // Порог взят долей полотна, а не числом: он переживёт смену `ICON_SIZE` и рисунка.
    // Десятая часть стоит в семь раз ниже измеренного и отделяет настоящий рисунок от россыпи
    // в несколько точек, которая в области уведомлений всё равно невидима.
    let opaque = 0;
    for (let i = 3; i < buf.length; i += 4) if (buf[i] !== 0) opaque += 1;
    if (opaque < Math.round(size * size * ICON_MIN_OPAQUE_SHARE)) {
      say(`значок вышел почти прозрачным: ${opaque} непрозрачных точек из ${size * size}`);
      return null;
    }

    const image = nativeImage.createFromBitmap(buf, { width: size, height: size });
    return image.isEmpty() ? null : image;
  } catch {
    return null;
  }
}

/** Строка-подпись о демоне. Владение показывается словом, а не номером процесса. */
function daemonLabel() {
  const state = daemonState();
  const version = state.version ? ` (${state.version})` : '';
  return state.owned ? `Демон: свой${version}` : `Демон: внешний${version}`;
}

/**
 * Шаблон меню — отдельной функцией, чтобы его можно было прочитать не создавая трея.
 * Этим пользуется постоянная проверка оболочки (`pult/tools/shell-check.mjs`): пункт «Выход»
 * обязан существовать и нести обработчик, иначе приложение становится незакрываемым.
 */
export function menuTemplate() {
  return [
    { label: 'Показать пульт', click: () => handlers.onShow() },
    { label: 'Открыть страницу в браузере', click: () => shell.openExternal(PULT_URL) },
    { label: daemonLabel(), enabled: false },
    { type: 'separator' },
    { label: 'Выход', click: () => handlers.onQuit() },
  ];
}

function rebuildMenu() {
  if (!tray) return;
  tray.setContextMenu(Menu.buildFromTemplate(menuTemplate()));
}

/**
 * Завести значок.
 *
 * ВОЗВРАЩАЕТСЯ ОТЧЁТ, А НЕ ОБЪЕКТ, и это несущее изменение (находка человека 02.09.2026):
 * от того, получился трей или нет, зависит поведение кнопки закрытия окна. Пока `createTray()`
 * молча отдавала трей с ПУСТОЙ картинкой, «значка не видно» и «значок есть» были для главного
 * процесса одним и тем же, а окно пряталось в невидимое место — приложение оставалось жить
 * без единого способа его закрыть, кроме диспетчера задач.
 *
 * Поля отчёта: `ok` — трей годен как способ вернуться и выйти; `iconEmpty` — картинка
 * не построилась (значок был бы невидим); `error` — `new Tray` бросил.
 */
export function createTray(options = {}) {
  handlers = {
    onShow: options.onShow || (() => {}),
    onQuit: options.onQuit || (() => {}),
  };
  const icon = buildIcon();
  if (!icon) say('иконка трея не построилась — значок был бы невидим, трей негоден');

  try {
    tray = new Tray(icon || nativeImage.createEmpty());
  } catch (e) {
    tray = null;
    const error = (e && e.message) || 'без причины';
    say(`трей не создался: ${error}`);
    return { ok: false, tray: null, iconEmpty: !icon, error };
  }

  tray.setToolTip(tipText);
  rebuildMenu();
  // ВТОРАЯ ПОЛОВИНА ПРОВЕРКИ — И ОНА СПРАШИВАЕТ ДРУГОЕ, а не то же самое дважды.
  //
  // `buildIcon()` считает непрозрачные точки в СВОЁМ буфере; здесь спрашивается БИБЛИОТЕКА,
  // получилось ли у неё изображение вообще. Предикаты разные намеренно: две половины, задающие
  // один и тот же вопрос, промахиваются вместе и избыточностью не являются — этой же ошибкой
  // раньше болели `mergeRows()` и `rootDenyMatch()` (находка ревью 02.09.2026).
  const usable = Boolean(icon) && !icon.isEmpty();
  return { ok: usable, tray, iconEmpty: !usable, error: null };
}

/** Подсказка иконки. Очистку и потолок делает вызывающий — там же, где остальной чужой текст. */
export function setTrayTip(text) {
  tipText = text || 'Пульт';
  if (!tray) return;
  tray.setToolTip(tipText);
  // Заодно освежается подпись о демоне: состояние могло смениться (свой процесс мог умереть).
  rebuildMenu();
}

export function destroyTray() {
  if (!tray) return;
  tray.destroy();
  tray = null;
}
