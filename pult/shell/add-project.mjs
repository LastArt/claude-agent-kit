#!/usr/bin/env node
/**
 * ЗАВЕСТИ ПРОЕКТ В РЕЕСТРЕ: запуск готового инструмента кита подпроцессом.
 *
 * Этот модуль ЗАМЕНИЛ СОБОЙ маршрут записи в реестр, снятый по итогам круга 1 аудита.
 * Записи в реестр по HTTP нет и не будет: запрет «маршрута, принимающего путь проекта
 * из запроса, у демона нет и быть не должно» записан в трёх местах (докблок
 * `pult/lib/pty-socket.mjs`, раздел про сессии в `pult/docs/ARCHITECTURE.md`, шапка
 * `pult/tools/write-scope-check.mjs`) и переписыванию не подлежит.
 *
 * ВХОД — АБСОЛЮТНЫЙ ПУТЬ ИЗ СИСТЕМНОГО ДИАЛОГА, И ДРУГОГО ИСТОЧНИКА У МОДУЛЯ НЕТ. Путь
 * рождается в главном процессе (`pult/shell/main.mjs`), со страницы не приходит ни в каком
 * виде и НА СТРАНИЦУ НЕ ВОЗВРАЩАЕТСЯ НИКОГДА. На этом держится свойство, ради которого
 * снимался маршрут: чужой скрипт на странице не может назначить корень проекта, потому что
 * назначать его нечем.
 *
 * ВСЮ САНИТАРИЮ ПУТИ ДЕЛАЕТ ИНСТРУМЕНТ, а не этот модуль: нулевой байт и управляющие
 * символы, потолок длины, отказ на сетевой форме, `resolve` плюс `realpath` ДО записи,
 * «каталог, а не симлинк на каталог», запрещённый корень и отсутствие дублей. Второй копии
 * этих проверок здесь нет намеренно — разошлись бы.
 *
 * РАЗДЕЛЕНИЕ ПОТОКОВ — ПРАВИЛО, А НЕ ДЕТАЛЬ. Человеку в окно уходит ТОЛЬКО ПОТОК ОШИБОК:
 * инструмент не печатает в него присланный путь ни в одной ветви. Стандартный вывод, где
 * он перечисляет ВСЕ записи реестра с абсолютными путями, остаётся в журнале оболочки
 * и в возвращаемое значение не попадает.
 *
 * ОСТАТОК, КОТОРЫЙ НАЗЫВАЕТСЯ ВСЛУХ: инструмент, убитый по таймауту, может оставить свой
 * временный файл в каталоге настроек рядом с реестром. Сам реестр при этом цел — запись
 * атомарна; временный файл человек видит рядом с реестром и удаляет.
 */

import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { capText, isPlainFile, realPath, sanePath } from '../lib/fs-safe.mjs';
import { projectId } from '../lib/registry.mjs';
import { DAEMON_DIR, childEnv, findNode, percentUnsafe, runCapped } from './daemon.mjs';

// --- константы: живут рядом с потребителем -----------------------------------

/** Инструмент читает реестр и пишет его целиком; секунд ему хватает с запасом. */
const TOOL_TIMEOUT_MS = 15000;

/** Потолок на КАЖДЫЙ поток инструмента по отдельности. */
const TOOL_MAX_BYTES = 64 * 1024;

/** Потолок текста отказа, уходящего человеку в окно. */
const TOOL_ERR_MAX = 2000;

/** Длина строки журнала — та же дисциплина, что у вывода демона. */
const LOG_LINE_MAX = 500;

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** Путь к инструменту считается ОТ АДРЕСА ЭТОГО МОДУЛЯ, а не от рабочего каталога. */
const TOOL = path.join(HERE, '..', 'tools', 'registry-add.mjs');

const say = (s) => process.stdout.write(`[shell] ${s}\n`);

const fail = (code, message) => ({ ok: false, code, message });

/** Вывод инструмента — в журнал оболочки построчно и с потолком длины строки. */
function logStream(text, tag) {
  for (const line of String(text).split(/\r?\n/)) {
    if (!line) continue;
    say(`${tag}: ${line.length > LOG_LINE_MAX ? `${line.slice(0, LOG_LINE_MAX)}…` : line}`);
  }
}

/**
 * Завести выбранный каталог проектом.
 *
 * @param {string} chosen абсолютный путь из системного диалога
 * @returns {Promise<{ok: true, id: string|null}|{ok: false, code: string, message: string}>}
 *          наружу уходит ТОЛЬКО идентификатор проекта: по нему страница выбирает проект
 *          в списке. Пути в ответе нет.
 */
export async function addProjectByPath(chosen) {
  // Дешёвая проверка входа. Всю настоящую санитарию делает инструмент; здесь ловится только
  // то, после чего запускать его бессмысленно: пустая строка и относительный путь (инструмент
  // разрешил бы его от СВОЕГО рабочего каталога, то есть завёл бы не тот проект).
  const raw = String(chosen == null ? '' : chosen);
  if (!sanePath(raw) || !path.isAbsolute(raw)) {
    return fail('bad_path', 'выбранный путь не годится: ожидается абсолютный путь к каталогу');
  }

  // Инструмент обязан быть обычным файлом. Нет — отказ с причиной, а не запуск чего попало.
  if (!(await isPlainFile(TOOL))) {
    return fail('tool_missing', 'инструмент добавления проекта не найден рядом с пультом');
  }

  // ФОРМА ЗАПУСКА БЕРЁТСЯ ЦЕЛИКОМ У ТОГО, КТО ЕЁ РАЗРЕШИЛ, и по частям не пересобирается:
  // поле файла из неё здесь не берётся вовсе.
  const node = await findNode();
  if (!node.ok) return node;

  const args = [TOOL, raw];

  // ЗНАК ПРОЦЕНТА ПРОВЕРЯЕТСЯ ПО ВСЕМУ НАБОРУ АРГУМЕНТОВ, а не только по выбранному пути:
  // путь к самому инструменту считается от расположения репозитория и уезжает в ту же
  // командную строку `cmd /c`. Подстановка по процентам идёт даже внутри кавычек, и в реестр
  // молча попал бы ДРУГОЙ каталог.
  if (percentUnsafe(node.form, args)) {
    return fail('percent_in_path', [
      'В пути есть знак процента, а найденный Node запускается через командный файл.',
      '',
      'Интерпретатор команд подставляет значение переменной окружения по процентам даже',
      'внутри кавычек, поэтому в реестр попал бы другой каталог. Отказываюсь молча портить путь.',
    ].join('\n'));
  }

  const run = await runCapped(node.form, args, {
    cwd: DAEMON_DIR,
    env: childEnv(),
    timeoutMs: TOOL_TIMEOUT_MS,
    maxBytes: TOOL_MAX_BYTES,
  });
  if (!run.ok) return run;

  // Стандартный вывод — ТОЛЬКО в журнал. В ответ он не попадает ни одной строкой.
  logStream(run.stdout, 'registry-add');

  if (run.killed) {
    return fail('tool_timeout', [
      'Инструмент добавления проекта не уложился в отведённое время и снят.',
      '',
      'Реестр при этом цел: запись в него атомарна. Рядом с реестром мог остаться временный',
      'файл — его можно удалить.',
    ].join('\n'));
  }

  if (run.code !== 0) {
    // Наружу идёт ТЕКСТ ПОТОКА ОШИБОК КАК ЕСТЬ — очищенный и обрезанный, без пересказа:
    // инструмент объясняет отказ лучше, чем мог бы объяснить пересказ.
    const text = capText(run.stderr, TOOL_ERR_MAX).text.trim();
    logStream(run.stderr, 'registry-add');
    return fail('tool_refused', text || `инструмент отказал, код ${run.code}`);
  }

  // ИДЕНТИФИКАТОР СЧИТАЕТСЯ ТЕМИ ЖЕ ФУНКЦИЯМИ, ЧТО У ИНСТРУМЕНТА, а не разбором его вывода:
  // разбор чужого текста завёл бы второй источник правды о том, что записано в реестр.
  const real = await realPath(raw);
  const id = real.ok ? projectId(real.path) : null;
  say(`проект заведён, идентификатор ${id || 'не посчитан'}`);
  return { ok: true, id };
}
